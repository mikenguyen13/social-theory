#!/usr/bin/env Rscript
# tools/merge_bib.R -- merge bib/*.bib into the single references.bib used by the book.
# Entries are de-duplicated by key; chapter files (bib/NN.bib) take precedence over
# legacy files (bib/legacy-*.bib), and corrections in bib/corrections.bib override all.
# Usage: Rscript tools/merge_bib.R

read_entries <- function(path) {
  txt <- paste(readLines(path, warn = FALSE, encoding = "UTF-8"), collapse = "\n")
  starts <- gregexpr("(?m)^\\s*@[A-Za-z]+\\s*[{]", txt, perl = TRUE)[[1]]
  if (starts[1] == -1) return(list())
  ends <- c(starts[-1] - 1, nchar(txt))
  chunks <- trimws(substring(txt, starts, ends))
  keys <- trimws(sub("^@[A-Za-z]+\\s*[{]\\s*([^,]+),.*$", "\\1", chunks))
  # Ignore BibTeX @comment/@preamble/@string blocks.
  keep <- !grepl("^@(comment|preamble|string)", chunks, ignore.case = TRUE)
  setNames(as.list(chunks[keep]), keys[keep])
}

files <- Sys.glob("bib/*.bib")
corrections <- files[basename(files) == "corrections.bib"]
legacy <- files[grepl("^legacy-", basename(files))]
chapters <- setdiff(files, c(corrections, legacy))

entries <- list()
add <- function(new, override = FALSE) {
  for (k in names(new)) if (override || is.null(entries[[k]])) entries[[k]] <<- new[[k]]
}
for (f in sort(chapters)) add(read_entries(f))
for (f in legacy) add(read_entries(f))
for (f in corrections) add(read_entries(f), override = TRUE)

entries <- entries[order(tolower(names(entries)))]
header <- c("% references.bib -- GENERATED by tools/merge_bib.R. Do not edit by hand;",
            "% edit bib/<chapter>.bib (or bib/corrections.bib) and re-run the script.", "")
writeLines(c(header, paste0(unlist(entries), "\n")), "references.bib", useBytes = TRUE)
cat("references.bib written with", length(entries), "entries from", length(files), "files\n")
